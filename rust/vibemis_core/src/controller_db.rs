pub fn guess_controller_type(vendor_id: i32, product_id: i32) -> i8 {
    let dev_id = ((vendor_id as u32 & 0xFFFF) << 16) | (product_id as u32 & 0xFFFF);
    for &(id, ctype) in CONTROLLERS {
        if id == dev_id {
            return ctype;
        }
    }
    VB_CTYPE_UNKNOWN
}

pub fn guess_controller_has_paddles(vendor_id: i32, product_id: i32) -> bool {
    let vid = (vendor_id & 0xFFFF) as u16;
    let pid = (product_id & 0xFFFF) as u16;
    let is_xbox_elite = vid == 0x045e && matches!(pid, 0x02e3 | 0x0b00 | 0x0b05 | 0x0b22);
    let is_dualsense_edge = vid == 0x054c && pid == 0x0df2;
    is_xbox_elite || is_dualsense_edge
}

pub fn guess_controller_has_share_button(vendor_id: i32, product_id: i32) -> bool {
    let vid = (vendor_id & 0xFFFF) as u16;
    let pid = (product_id & 0xFFFF) as u16;
    match vid {
        0x045e => matches!(pid, 0x0b12 | 0x0b13),
        0x0e6f => matches!(pid, 0x02d6 | 0x02d9 | 0x02da),
        0x20d6 => (0x2001..=0x201a).contains(&pid) || matches!(pid, 0x4001 | 0x890b | 0x4002),
        0x0f0d => matches!(pid, 0x0150 | 0x014f),
        0x1532 => matches!(pid, 0x0a29 | 0x0a2e),
        0x044f => pid == 0xd012,
        0x10f5 => matches!(pid, 0x7013 | 0x7009),
        0x2dc8 => pid == 0x2002,
        0x3537 => pid == 0x1001,
        _ => false,
    }
}
